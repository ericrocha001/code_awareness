const fs = require('node:fs')
const path = require('node:path')
const { buildSync } = require('esbuild')

exports.run = async ctx => {
  const backend = path.join(ctx.evidenceDir, 'backend.cjs')
  buildSync({ stdin: { contents: "export { AcademyService } from './src/main/academy/academy-service'; export { registerAcademyHandlers } from './src/main/ipc/academy-handler'", resolveDir: ctx.projectRoot }, bundle: true, outfile: backend, platform: 'node', format: 'cjs', external: ['electron', 'better-sqlite3'] })
  const { AcademyService, registerAcademyHandlers } = require(backend)
  const database = path.join(ctx.temporary, 'academy.db')
  let service = new AcademyService(database)
  try {
    const project = path.join(ctx.temporary, 'project')
    fs.mkdirSync(project)
    await service.registerDestination(project, 'Isolated acceptance project')
    service.watcher.stop()
    const pkg = body => ({ skillMd: `---\nname: activation-fixture\ndescription: Reversible activation acceptance\n---\n${body}\n`, artifacts: {} })
    const skill = await service.create({ package: pkg('original'), scope: 'GLOBAL', origin: 'UI' })
    await service.waitForReconciliation()
    registerAcademyHandlers(service)
    const preload = path.join(ctx.temporary, 'preload.cjs')
    buildSync({ entryPoints: [path.join(ctx.projectRoot, 'src/main/preload.ts')], bundle: true, outfile: preload, platform: 'node', format: 'cjs', external: ['electron'] })
    ctx.window.webContents.session.setPreloads([preload])
    buildSync({ entryPoints: [path.join(__dirname, 'academy-conflicts-fixture.tsx')], bundle: true, outfile: path.join(ctx.temporary, 'fixture.js'), platform: 'browser', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' }, loader: { '.woff': 'dataurl', '.woff2': 'dataurl', '.ttf': 'dataurl' } })
    const page = path.join(ctx.temporary, 'index.html')
    fs.writeFileSync(page, '<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="fixture.css"><style>html,body,#root{height:100%;margin:0}body{background:var(--bg-primary);color:var(--text-primary)}</style></head><body><div id="root"></div><script src="fixture.js"></script></body></html>')
    await ctx.load(page)
    await ctx.viewport(1440, 900)
    await ctx.waitFor(() => !!document.querySelector('.academy-activation-switch'))
    await ctx.click('.academy-skill-item')
    await ctx.waitFor(() => !!document.querySelector('[aria-label="Ativação da Skill selecionada"]'))
    await ctx.capture('active-dark')
    await ctx.click('.academy-activation-switch')
    await ctx.waitFor(() => document.querySelector('.academy-activation-switch')?.getAttribute('aria-checked') === 'false' && !document.querySelector('.academy-activation-switch').disabled)
    await service.waitForReconciliation()
    ctx.check('Real catalog IPC disables without changing content or selection', service.get(skill.id).status === 'DISABLED' && service.get(skill.id).currentVersion === 1 && await ctx.evaluate(() => document.querySelector('.academy-skill-heading h2').textContent === 'activation-fixture'))
    for (const directory of ['.skills', '.claude/skills', '.agents/skills']) ctx.check(`Managed ${directory} withdrawn`, !fs.existsSync(path.join(project, directory, skill.name)))
    await ctx.capture('disabled-dark')
    await ctx.evaluate(() => [...document.querySelectorAll('button')].find(button => button.textContent === 'Editar').click())
    await ctx.evaluate(() => { document.querySelector('[aria-label="Editar SKILL.md"]').select() })
    ctx.window.webContents.insertText(pkg('edited while disabled').skillMd)
    await ctx.evaluate(() => [...document.querySelectorAll('button')].find(button => button.textContent === 'Salvar').click())
    await ctx.waitFor(() => !document.querySelector('[aria-label="Editar SKILL.md"]'))
    await service.waitForReconciliation()
    ctx.check('Disabled UI edit creates version without distribution', service.get(skill.id).status === 'DISABLED' && service.get(skill.id).currentVersion === 2 && !fs.existsSync(path.join(project, '.skills', skill.name)))
    await ctx.click('[aria-label="Ativação da Skill selecionada"]')
    await ctx.waitFor(() => document.querySelector('.academy-activation-switch')?.getAttribute('aria-checked') === 'true' && !document.querySelector('.academy-activation-switch').disabled)
    await service.waitForReconciliation()
    ctx.check('Reactivation delivers the latest version', fs.readFileSync(path.join(project, '.agents/skills', skill.name, 'SKILL.md'), 'utf8').includes('edited while disabled'))
    service.store.setEnabled(skill.id, false, 3)
    await ctx.click('.academy-activation-switch')
    await ctx.waitFor(() => document.querySelector('[role="status"]')?.textContent.includes('activation changed') && document.querySelector('.academy-activation-switch')?.getAttribute('aria-checked') === 'false')
    ctx.check('Stale UI CAS refreshes persisted disabled state', service.get(skill.id).stateRevision === 4 && service.get(skill.id).status === 'DISABLED')
    await ctx.viewport(1000, 760)
    await ctx.evaluate(() => { document.body.dataset.theme = 'light' })
    await ctx.overflow()
    await ctx.capture('conflict-light')
    await service.close()
    service = new AcademyService(database)
    ctx.check('SQLite restart preserves activation and immutable history', service.get(skill.id).status === 'DISABLED' && service.get(skill.id).stateRevision === 4 && service.history(skill.id, { version: 1 }).packageHash === skill.current.packageHash)
  } finally {
    await service.close()
    ctx.window.webContents.session.setPreloads([])
  }
}

const fs = require('node:fs')
const path = require('node:path')
const { buildSync } = require('esbuild')
const Database = require('better-sqlite3')

exports.run = async ctx => {
  const backend = path.join(ctx.evidenceDir, 'backend.cjs')
  buildSync({ stdin: { contents: "export { AcademyService } from './src/main/academy/academy-service'; export { registerAcademyHandlers } from './src/main/ipc/academy-handler'", resolveDir: ctx.projectRoot }, bundle: true, outfile: backend, platform: 'node', format: 'cjs', external: ['electron', 'better-sqlite3'] })
  const { AcademyService, registerAcademyHandlers } = require(backend)
  const service = new AcademyService(path.join(ctx.temporary, 'academy.db'))
  const pkg = (name, body) => ({ skillMd: `---\nname: ${name}\ndescription: Conflict acceptance\n---\n${body}\n`, artifacts: {} })
  try {
    const destination = await service.registerDestination(path.join(ctx.temporary, 'project'), 'Acceptance project')
    const historical = await service.create({ package: pkg('historical-skill', 'Historical text'), scope: 'GLOBAL', origin: 'UI' })
    await service.update({ skillId: historical.id, expectedVersion: 1, package: pkg('historical-skill', 'Current canonical text'), origin: 'MCP' })
    const external = await service.create({ package: pkg('external-skill', 'Canonical text'), scope: 'GLOBAL', origin: 'UI' })
    const externalFile = path.join(destination.path, '.skills/external-skill/SKILL.md')
    fs.writeFileSync(externalFile, pkg('external-skill', 'Reviewed external text\n' + 'Long source content\n'.repeat(55)).skillMd)
    await service.watcher.ingest(destination.id, 'external-skill')
    const db = new Database(service.store.databasePath)
    try {
      const insert = db.prepare("INSERT INTO academy_conflicts VALUES(?,?, 'FILESYSTEM',1,1,?,?,?,?, 'OPEN',?,NULL)")
      const directory = path.join(destination.path, '.skills/historical-skill')
      for (let index = 0; index < 200; index++) insert.run(`legacy-${index}`, historical.id, index < 174 ? null : JSON.stringify(historical.current.package), index < 174 ? `INVALID:SKILL.md not found in ${directory}` : historical.current.packageHash, destination.id, directory, new Date().toISOString())
    } finally { db.close() }
    let reviews = 0
    const review = service.reviewConflict.bind(service)
    service.reviewConflict = async id => { reviews++; return review(id) }
    registerAcademyHandlers(service)
    const preload = path.join(ctx.temporary, 'preload.cjs')
    buildSync({ entryPoints: [path.join(ctx.projectRoot, 'src/main/preload.ts')], bundle: true, outfile: preload, platform: 'node', format: 'cjs', external: ['electron'] })
    ctx.window.webContents.session.setPreloads([preload])
    buildSync({ entryPoints: [path.join(__dirname, 'academy-conflicts-fixture.tsx')], bundle: true, outfile: path.join(ctx.temporary, 'fixture.js'), platform: 'browser', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' }, loader: { '.woff': 'dataurl', '.woff2': 'dataurl', '.ttf': 'dataurl' } })
    const page = path.join(ctx.temporary, 'index.html')
    fs.writeFileSync(page, '<!doctype html><html><head><meta charset="utf-8"><link rel="stylesheet" href="fixture.css"><style>html,body,#root{height:100%;margin:0}body{background:var(--bg-primary);color:var(--text-primary)}</style></head><body><div id="root"></div><script src="fixture.js"></script></body></html>')
    await ctx.load(page)
    await ctx.viewport(1440, 900)
    await ctx.waitFor(() => document.querySelectorAll('.academy-conflict-group').length === 3)
    ctx.check('Initial load uses only summaries and distinct counts', reviews === 0 && service.snapshot().conflicts.length === 3 && !JSON.stringify(service.snapshot().conflicts).includes('skillMd'))
    await ctx.overflow()
    const before = await ctx.capture('grouped-dark')
    await ctx.evaluate(() => [...document.querySelectorAll('.academy-conflict-group')].find(button => button.textContent.includes('Conteúdo divergente')).click())
    await ctx.click('.academy-conflict-items button')
    await ctx.waitFor(() => !!document.querySelector('.academy-conflict-diff'))
    ctx.check('Requested inspector exposes actual package diff with local scroll', reviews === 1 && await ctx.evaluate(() => { const diff = document.querySelector('.academy-conflict-diff'); return diff.textContent.includes('+Reviewed external text') && diff.scrollHeight > diff.clientHeight }))
    await ctx.capture('review-dark')
    await ctx.viewport(1000, 760)
    await ctx.evaluate(() => { document.body.dataset.theme = 'light' })
    await ctx.overflow()
    await ctx.capture('review-medium-light')
    await ctx.click('.academy-conflict-inspector .academy-danger-button')
    await ctx.waitFor(() => !!document.querySelector('[role="alertdialog"]'))
    ctx.check('Adoption waits for explicit confirmation', service.get(external.id).currentVersion === 1)
    await ctx.capture('adoption-confirmation-light')
    await ctx.click('[role="alertdialog"] .academy-danger-button')
    await ctx.waitFor(() => !document.querySelector('.academy-conflict-inspector'))
    ctx.check('Confirmed adoption creates immutable canonical version through real IPC', service.get(external.id).currentVersion === 2 && service.history(external.id).length === 2 && service.get(external.id).current.package.skillMd.includes('Reviewed external text'))
    await ctx.viewport(1440, 900)
    await ctx.evaluate(() => { document.body.dataset.theme = 'dark' })
    await ctx.click('.academy-conflicts-summary > .academy-secondary-button')
    await ctx.waitFor(() => !!document.querySelector('.academy-batch-entries'))
    ctx.check('Dry-run leaves 200 records unresolved', service.snapshot().conflicts.reduce((sum, item) => sum + item.occurrenceCount, 0) === 200)
    await ctx.window.webContents.capturePage()
    await ctx.capture('batch-preview-dark')
    await ctx.click('.academy-conflict-inspector footer button')
    await ctx.waitFor(() => !!document.querySelector('[role="alertdialog"]'))
    await ctx.click('[role="alertdialog"] .academy-primary-button')
    await ctx.waitFor(() => !document.querySelector('.academy-conflict-card'))
    ctx.check('Certified batch clears duplicates without canonical regression', service.store.listConflicts().length === 0 && service.get(historical.id).currentVersion === 2 && service.get(historical.id).current.package.skillMd.includes('Current canonical text'))
    await ctx.overflow()
    const after = await ctx.capture('clean-dark')
    ctx.check('Native rendering changes pixels across resolution', !before.toPNG().equals(after.toPNG()))
  } finally {
    service.close()
    ctx.window.webContents.session.setPreloads([])
  }
}

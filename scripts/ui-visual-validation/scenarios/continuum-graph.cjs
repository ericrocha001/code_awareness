const fs = require('node:fs')
const path = require('node:path')
const { buildSync } = require('esbuild')

exports.run = async ctx => {
  const backend = path.join(ctx.evidenceDir, 'backend.cjs')
  buildSync({ stdin: { contents: "export { registerContinuumHandlers } from './src/main/ipc/continuum-handler'; export { RepositoryContinuumSession } from './src/main/continuum/project-continuum-session'", resolveDir: ctx.projectRoot }, bundle: true, outfile: backend, platform: 'node', format: 'cjs', alias: { sharp: require.resolve('sharp') }, external: ['electron', 'better-sqlite3', require.resolve('sharp')] })
  const { registerContinuumHandlers, RepositoryContinuumSession } = require(backend)
  const root = path.join(ctx.temporary, 'repository-A'), other = path.join(ctx.temporary, 'repository-B')
  fs.mkdirSync(root); fs.mkdirSync(other)
  const session = new RepositoryContinuumSession(path.join(ctx.temporary, 'storage'), { findByPath: candidate => ({ id: candidate === root ? 'graph-A' : 'graph-B', localCheckout: { path: candidate } }) })
  session.activate(root)
  const service = session.getActiveService()
  const publish = (name, extra = '', body = '# Exact inspection\n\nRead only when selected.') => service.publish(`---\nname: ${name}\ndescription: SQLite migration graph evidence\n${/^kind:/m.test(extra) ? '' : 'kind: DECISION\n'}${/^status:/m.test(extra) ? '' : 'status: VALIDATED\n'}occurred: 2026-10-12T00:30:00-03:00\n${extra}---\n${body}`).artifactId
  const target = publish('SQLite migration foundation', 'executionId: acceptance-execution\n')
  const source = publish('SQLite migration rollback — selected artifact with a deliberately long title', `executionId: acceptance-execution\nrelations:\n  - artifactId: ${target}\n    kind: implements\n`)
  const derived = publish('Derived reference', '', `# Reference\n\nSee ${target}.`)
  const candidate = publish('SQLite migration transaction')
  const pixels = await require('sharp')({ create: { width: 32, height: 16, channels: 4, background: '#7852ee' } }).webp({ lossless: true }).toBuffer()
  const visual = (await service.publishVisual('---\nname: Isolated WebP\ndescription: Canonical isolated visual reference\nkind: VISUAL_REFERENCE\nstatus: PENDING\n---\n# Visual artifact\n', pixels)).artifactId
  const { ipcMain } = require('electron')
  const original = ipcMain.handle
  const reads = { graphs: [], suggestions: [], details: [] }
  let failNext = false
  ipcMain.handle = function(channel, handler) {
    original.call(this, channel, async (...args) => {
      if (channel === 'continuum:graph') { reads.graphs.push(args[1]); if (failNext) { failNext = false; throw new Error('Graph acceptance injected failure') } }
      if (channel === 'continuum:suggestions') reads.suggestions.push(args[1])
      if (channel === 'continuum:get') reads.details.push(args[2])
      return handler(...args)
    })
  }
  registerContinuumHandlers(session)
  ipcMain.handle = original
  try {
    const preload = path.join(ctx.temporary, 'preload.cjs')
    buildSync({ entryPoints: [path.join(ctx.projectRoot, 'src/main/preload.ts')], bundle: true, outfile: preload, platform: 'node', format: 'cjs', external: ['electron'] })
    ctx.window.webContents.session.setPreloads([preload])
    buildSync({ entryPoints: [path.join(__dirname, 'continuum-graph-fixture.tsx')], bundle: true, outfile: path.join(ctx.temporary, 'fixture.js'), platform: 'browser', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' }, loader: { '.woff': 'file', '.woff2': 'file', '.ttf': 'file' } })
    const csp = /<meta\s+http-equiv="Content-Security-Policy"\s+content="([^"]+)"/.exec(fs.readFileSync(path.join(ctx.projectRoot, 'src/renderer/index.html'), 'utf8'))[1]
    const page = path.join(ctx.temporary, 'index.html')
    fs.writeFileSync(page, `<!doctype html><html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="${csp}"><link rel="stylesheet" href="fixture.css"><style>html,body,#root{height:100%;margin:0}</style></head><body><div id="root"></div><script src="fixture.js"></script></body></html>`)
    await ctx.window.loadFile(page, { query: { repositoryPath: root } })
    await ctx.viewport(1440, 900)
    await ctx.waitFor(() => document.querySelectorAll('.continuum-item').length === 5)
    await ctx.click('[role=tab]:last-child')
    await ctx.waitFor(() => document.querySelectorAll('[aria-label="Selecionar artifact no grafo"] option').length === 6)
    ctx.check('Graph default excludes suggestions and whole-document reads', reads.suggestions.length === 0 && reads.details.length === 0)
    ctx.check('Production IPC caps and scope', reads.graphs.every(request => request.repositoryId === 'graph-A' && request.nodeLimit <= 100 && request.edgeLimit <= 500))
    const choose = (label, value) => ctx.evaluate((label, value) => { const control = document.querySelector(`[aria-label="${label}"]`); control.value = value; control.dispatchEvent(new Event('change', { bubbles: true })) }, label, value)
    await choose('Selecionar artifact no grafo', visual)
    await ctx.waitFor(() => document.querySelector('.continuum-visual-preview')?.naturalWidth === 32 || !!document.querySelector('.continuum-inspector [role=alert]'))
    ctx.check('Visual media renders under production CSP', await ctx.evaluate(() => document.querySelector('.continuum-visual-preview')?.naturalWidth === 32))
    ctx.check('Blob scripts remain blocked by production CSP', await ctx.evaluate(() => new Promise(resolve => {
      const url = URL.createObjectURL(new Blob(['window.blobScriptExecuted = true'], { type: 'text/javascript' }))
      const script = document.createElement('script'); script.src = url
      script.onerror = () => { URL.revokeObjectURL(url); script.remove(); resolve(!window.blobScriptExecuted) }
      script.onload = () => { URL.revokeObjectURL(url); script.remove(); resolve(false) }
      document.body.appendChild(script)
    })))
    await choose('Selecionar artifact no grafo', source)
    await ctx.waitFor(() => !!document.querySelector('.continuum-markdown h1'))
    ctx.check('Shared Inspector and only selected details', reads.details.length === 2 && reads.details.at(-1) === source)
    await ctx.evaluate(() => { const control = [...document.querySelectorAll('.continuum-graph-controls input')].find(input => input.parentElement.textContent.includes('Sugestões')); control.click() })
    await ctx.waitFor(() => [...document.querySelectorAll('[aria-label="Inspecionar relação"] option')].some(option => option.textContent.startsWith('SUGGESTED')))
    await ctx.evaluate(() => { const control = document.querySelector('[aria-label="Inspecionar relação"]'); control.value = [...control.options].find(option => option.textContent.startsWith('SUGGESTED')).value; control.dispatchEvent(new Event('change', { bubbles: true })) })
    ctx.check('All provenance line forms and candidate evidence', await ctx.evaluate(() => ['declared', 'derived', 'suggested'].every(kind => !!document.querySelector('.continuum-graph-legend .' + kind)) && document.querySelector('.continuum-graph-relation').textContent.includes('SUGGESTED')))
    ctx.check('Suggestion did not promote a relation', service.get(source).revision === 1 && !service.get(source).metadata.relations.some(edge => edge.artifactId === candidate))
    await ctx.overflow()
    await ctx.capture('graph-wide-dark-evidence')
    await ctx.click('[aria-label="Ampliar grafo"]')
    await ctx.click('.continuum-graph-canvas')
    const beforePan = await ctx.evaluate(() => ({ ...document.querySelector('.continuum-graph-canvas')._cyreg.cy.pan() }))
    ctx.window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Left' }); ctx.window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Left' })
    ctx.check('Keyboard canvas focus', await ctx.evaluate(() => document.activeElement.classList.contains('continuum-graph-canvas')))
    ctx.check('Native keyboard pans graph', await ctx.evaluate(before => document.querySelector('.continuum-graph-canvas')._cyreg.cy.pan().x === before.x + 40, beforePan))
    await ctx.click('.continuum-graph-controls button:nth-child(3)')
    const point = await ctx.evaluate(id => {
      const canvas = document.querySelector('.continuum-graph-canvas'), rect = canvas.getBoundingClientRect()
      const node = canvas._cyreg.cy.getElementById('artifact:' + id), position = node.renderedPosition()
      return { x: Math.round(rect.x + position.x), y: Math.round(rect.y + position.y), position: { ...node.position() } }
    }, source)
    ctx.window.webContents.sendInputEvent({ type: 'mouseMove', x: point.x, y: point.y })
    await ctx.waitFor(() => document.querySelector('.continuum-graph-tooltip')?.textContent.includes('deliberately long title'))
    ctx.check('Native hover reveals full artifact title', true)
    ctx.window.webContents.sendInputEvent({ type: 'mouseDown', x: point.x, y: point.y, button: 'left', clickCount: 1 })
    ctx.window.webContents.sendInputEvent({ type: 'mouseMove', x: point.x + 35, y: point.y + 20, button: 'left' })
    ctx.window.webContents.sendInputEvent({ type: 'mouseUp', x: point.x + 35, y: point.y + 20, button: 'left', clickCount: 1 })
    ctx.check('Native drag repositions node', await ctx.evaluate((id, before) => {
      const position = document.querySelector('.continuum-graph-canvas')._cyreg.cy.getElementById('artifact:' + id).position()
      return position.x !== before.x || position.y !== before.y
    }, source, point.position))
    await ctx.evaluate(() => { document.body.dataset.theme = 'light' })
    await ctx.capture('graph-wide-light')
    await ctx.viewport(1000, 760)
    await ctx.click('[aria-label="Fechar inspector"]')
    await ctx.overflow()
    await ctx.capture('graph-medium-light')
    await ctx.evaluate(() => { document.body.dataset.theme = 'dark' })
    await choose('Selecionar artifact no grafo', derived)
    await ctx.waitFor(() => document.querySelector('.continuum-inspector').classList.contains('open'))
    await ctx.capture('graph-medium-dark-inspector')
    await ctx.click('[aria-label="Fechar inspector"]')
    await ctx.click('[role=tab]:first-child')
    await ctx.waitFor(() => !document.querySelector('.continuum-graph-canvas'))
    ctx.check('Timeline survives Graph teardown', await ctx.evaluate(() => document.querySelectorAll('.continuum-item').length === 5))
  await ctx.click('.continuum-context-actions > button')
  await ctx.waitFor(() => !!document.querySelector('.continuum-facet-options'))
  await ctx.evaluate(() => { const label = [...document.querySelectorAll('.continuum-facet-options label')].find(label => label.textContent === 'occurred'); label.querySelector('input').click() })
  await ctx.waitFor(() => [...document.querySelectorAll('.continuum-facet-groups > details summary')].some(summary => summary.textContent === 'occurred'))
  await ctx.click('.continuum-context-actions > button')
  await ctx.waitFor(() => !document.querySelector('.continuum-facet-options'))
  await ctx.click('.continuum-context-actions > div button')
  await ctx.waitFor(() => [...document.querySelectorAll('.continuum-facet-groups details')].every(group => group.open))
    await ctx.click('[aria-label="occurred 2026-10"]')
    await ctx.click('[role=tab]:last-child')
    await ctx.waitFor(() => document.querySelectorAll('[aria-label="Selecionar artifact no grafo"] option').length === 5)
    ctx.check('Temporal filter survives view switch', reads.graphs.at(-1).periods.occurred.month === 10)
    await ctx.click('.continuum-context .continuum-pane-heading button')
    for (let i = 0; i < 95; i++) publish('Dense graph observation ' + i, `relations:\n  - artifactId: ${i % 2 ? source : target}\n    kind: related-to\n`)
    for (const id of [source, target]) { const artifact = service.get(id); service.update(id, artifact.revision, artifact.rawMarkdown + '\nDense corpus fixture.') }
    await ctx.waitFor(() => document.querySelector('[aria-label="Selecionar artifact no grafo"]').options.length === 51)
    ctx.check('Dense graph is a bounded incomplete subset', await ctx.evaluate(() => document.querySelector('.continuum-graph-footer').textContent.includes('recorte incompleto')))
    await ctx.viewport(1440, 900)
    await ctx.capture('graph-dense-dark')
    await ctx.evaluate(() => { document.body.dataset.theme = 'light' })
    await ctx.capture('graph-dense-light')
    await ctx.input('[aria-label="Buscar no Continuum"]', 'no-results-acceptance')
    await ctx.waitFor(() => document.querySelector('.continuum-graph-state')?.textContent.includes('Nenhum artifact'))
    await ctx.capture('graph-empty')
    failNext = true
    await ctx.click('[aria-label="Buscar no Continuum"]')
    ctx.window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'A', modifiers: ['control'] })
    ctx.window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'A', modifiers: ['control'] })
    ctx.window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Backspace' })
    ctx.window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Backspace' })
    await ctx.waitFor(() => document.querySelector('.continuum-graph-state[role=alert]'))
    await ctx.capture('graph-error')
    await ctx.click('.continuum-graph-state button')
    await ctx.waitFor(() => document.querySelector('[aria-label="Selecionar artifact no grafo"]').options.length === 51)
    session.activate(other)
    await ctx.evaluate(other => window.dispatchEvent(new CustomEvent('fixture-repository', { detail: other })), other)
    await ctx.waitFor(() => document.querySelector('.continuum-graph-state')?.textContent.includes('Nenhum artifact'))
    ctx.check('Repository switch has no stale graph or detail', await ctx.evaluate(() => document.querySelector('[aria-label="Selecionar artifact no grafo"]').options.length === 1 && !document.querySelector('.continuum-markdown h1')))
    await ctx.overflow()
  } finally { session.dispose() }
}

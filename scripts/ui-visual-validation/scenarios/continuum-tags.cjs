const sharp = require('sharp')
exports.run = async ctx => {
  const runtime = await require('./continuum-runtime.cjs').setup(ctx)
  const service = runtime.session.getActiveService()
  const text = '\uFEFF---\r\nname: Markdown acceptance\r\ndescription: Tags real runtime\r\nkind: DOCUMENT\r\ncustom: "keep" # exact\r\n---\r\n# Literal ç 🚀\r\n'
  const one = service.publish(text)
  const data = await sharp({ create: { width: 240, height: 120, channels: 4, background: '#7852ee80' } }).webp({ lossless: true }).toBuffer()
  const visual = await service.publishVisual('---\nname: Visual acceptance\ndescription: Immutable WebP\nkind: VISUAL_REFERENCE\n---\n# Visual\n', data)
  const set = async (label, value) => ctx.evaluate((label, value) => { const element = document.querySelector(`[aria-label="${label}"]`); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(element, value); element.dispatchEvent(new Event('input', { bubbles: true })) }, label, value)
  const create = async (slug, name) => {
    await set('Slug da tag', slug); await set('Nome da tag', name)
    await ctx.click('[aria-label="Criar tag"]')
    await ctx.waitFor(value => [...document.querySelectorAll('.continuum-tag-list code')].some(code => code.textContent === value), slug)
  }
  try {
    await runtime.open(); await ctx.viewport(1440, 900)
    await ctx.waitFor(() => document.querySelectorAll('.continuum-item').length === 2)
    await ctx.click('[aria-label="Gerenciar tags"]')
    await ctx.waitFor(() => !!document.querySelector('.continuum-tag-manager'))
    await create('architecture', 'Architecture'); await create('onboarding', 'Onboarding')
    await ctx.capture('tags-manager-dark')
    await ctx.click('[aria-label="Fechar tags"]')
    await ctx.click(`[data-artifact-id="${one.artifactId}"]`)
    await ctx.waitFor(() => document.querySelectorAll('.continuum-artifact-tags input').length === 2)
    await ctx.click('.continuum-artifact-tags label:first-of-type input')
    await ctx.waitFor(() => document.querySelector('.continuum-artifact-tags input')?.checked)
    await ctx.click('.continuum-artifact-tags label:last-of-type input')
    await ctx.waitFor(() => [...document.querySelectorAll('.continuum-artifact-tags input')].every(input => input.checked))
    ctx.check('Inspector writes both canonical tags with literal body and custom YAML preserved', service.get(one.artifactId).metadata.tags.length === 2 && service.get(one.artifactId).rawMarkdown.includes('custom: "keep" # exact\r\n') && service.get(one.artifactId).rawMarkdown.endsWith('# Literal ç 🚀\r\n'))
    await ctx.click(`[aria-label="Selecionar Visual acceptance para tags"]`)
    await ctx.click('[aria-label="Gerenciar tags"]')
    await ctx.waitFor(() => !!document.querySelector('[aria-label="Aplicar architecture à seleção"]'))
    await ctx.click('[aria-label="Aplicar architecture à seleção"]')
    await ctx.waitFor(() => !!document.querySelector('.continuum-tag-confirmation'))
    ctx.check('Batch does not mutate before confirmation', !service.get(visual.artifactId).metadata.tags)
    await ctx.evaluate(() => [...document.querySelectorAll('button')].find(button => button.textContent === 'Confirmar marcação').click())
    await ctx.waitFor(() => !document.querySelector('.continuum-tag-confirmation'))
    ctx.check('Batch affects exactly selected IDs and keeps WebP hash and bytes', service.get(visual.artifactId).metadata.tags.join() === 'architecture' && service.get(one.artifactId).metadata.tags.length === 2 && service.getVisual(visual.artifactId).data.equals(data) && service.getVisual(visual.artifactId).media.sha256 === visual.media.sha256)
    await ctx.click('[aria-label="Editar tag architecture"]')
    await set('Nome da tag', 'Architecture renamed'); await set('Cor da tag', '#112233')
    await ctx.click('[aria-label="Salvar tag"]')
    await ctx.waitFor(() => document.querySelector('.continuum-tag-list')?.textContent.includes('Architecture renamed'))
    ctx.check('Renaming display identity preserves canonical slug', service.tags().some(tag => tag.slug === 'architecture' && tag.name === 'Architecture renamed' && tag.color === '#112233'))
    runtime.session.deactivate(); runtime.session.activate(runtime.root)
    await runtime.open()
    await ctx.waitFor(() => document.querySelectorAll('.continuum-item').length === 2)
    await ctx.click('[aria-label="Gerenciar tags"]')
    await ctx.waitFor(() => document.querySelector('.continuum-tag-list')?.textContent.includes('Architecture renamed'))
    ctx.check('Catalog and membership survive a real SQLite session restart', runtime.session.getActiveService().tags().find(tag => tag.slug === 'architecture').count === 2)
    await ctx.click('[aria-label="Fechar tags"]')
    await ctx.click(`[data-artifact-id="${visual.artifactId}"]`)
    await ctx.waitFor(() => document.querySelector('.continuum-visual-preview')?.naturalWidth === 240)
    await ctx.overflow(); await ctx.capture('tags-inspector-dark')
    const denied = await ctx.evaluate(async () => { try { await window.codeAwareness.mutateContinuumTags({ repositoryId: 'acceptance-B', intent: 'delete', slug: 'architecture' }); return false } catch (error) { return String(error).includes('REPOSITORY_UNAVAILABLE') } })
    ctx.check('Wrong repository cannot mutate the active catalog', denied)
  } finally { runtime.close() }
}

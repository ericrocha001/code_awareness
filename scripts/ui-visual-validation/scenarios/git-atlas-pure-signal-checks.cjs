const fs = require('node:fs')
const path = require('node:path')
const { spawnSync } = require('node:child_process')

exports.run = async (ctx, { root, git, before, head, backend, waitForGit }) => {
  const settle = () => waitForGit(() => document.querySelector('.gm-history')?.getAttribute('aria-busy') === 'false')
  const close = async () => { await ctx.click('[aria-label="Fechar detalhes"]'); await ctx.waitFor(() => !document.querySelector('.gm-inspector')) }
  const operations = async () => { await ctx.click('[aria-label="Operações Git"]'); await waitForGit(() => !!document.querySelector('.gm-actions') && document.querySelector('.gm-inspector')?.getAttribute('aria-busy') === 'false') }
  const lookup = async sha => {
    await ctx.click('[aria-label="Mais opções do Atlas"]')
    await ctx.click('.gm-secondary-menu button')
    await ctx.input('[aria-label="SHA completo"]', sha)
    await ctx.click('.gm-sha-lookup button')
    await waitForGit(() => !!document.querySelector('[aria-label="Copiar SHA"]'))
  }
  const wheelPast = async () => {
    await ctx.evaluate(() => { const map = document.querySelector('.gm-atlas-scroll'); map.scrollLeft = 0; map.dispatchEvent(new Event('scroll')); map.dispatchEvent(new WheelEvent('wheel', { deltaX: -500, bubbles: true })) })
    await settle()
  }
  await ctx.viewport(1672, 941)
  ctx.check('Panorama has no reserved inspector, mode buttons, selectors or manual pagination', await ctx.evaluate(() => !document.querySelector('.gm-inspector') && !document.querySelector('.gm-load-more') && !document.querySelector('select') && document.querySelectorAll('[aria-label="Atualizar Git"]').length === 1 && !document.querySelector('[aria-label="Modo do Atlas"]')))
  await ctx.capture('pure-signal-panorama-dark')
  await ctx.click('.gm-commit.is-merge')
  await waitForGit(() => !!document.querySelector('.gm-commit-author'))
  ctx.check('Commit prioritizes author/SHA and hides technical provenance', await ctx.evaluate(() => document.querySelector('.gm-technical')?.open === false && (document.querySelector('.gm-inspector').textContent.match(/Origem: Não registrada/g) || []).length === 1))
  await ctx.click('.gm-files button')
  await waitForGit(() => !!document.querySelector('.gm-patch pre'))
  ctx.check('Actual merge patch remains on demand', await ctx.evaluate(() => document.querySelector('.gm-patch pre').textContent.includes('+topic')))
  ctx.window.webContents.sendInputEvent({ type: 'mouseMove', x: 10, y: 10 })
  await ctx.capture('pure-signal-commit-dark')
  await ctx.evaluate(() => { document.body.dataset.theme = 'light' })
  await ctx.capture('pure-signal-commit-light')
  await close()
  const comparisons = backend.metrics.compare.length
  await ctx.click('.gm-atlas-lane-label[data-track^="refs/heads/feature/"] button')
  await waitForGit(() => !!document.querySelector('.gm-branch-tip'))
  ctx.check('Branch focus does not query comparison until requested', backend.metrics.compare.length === comparisons)
  await ctx.capture('pure-signal-branch-light')
  await ctx.click('[aria-label="Comparar branch"]')
  await waitForGit(() => document.querySelector('.gm-comparison')?.textContent.includes('exclusivos da base'))
  ctx.check('Contextual comparison preserves real reachability', await ctx.evaluate(() => document.querySelector('.gm-comparison').textContent.includes('0 exclusivos do alvo')))
  await ctx.capture('pure-signal-comparison-light')
  await ctx.evaluate(() => { const select = document.querySelector('[aria-label="Referência em foco"]'); select.value = 'refs/heads/feature/inspector'; select.dispatchEvent(new Event('change', { bubbles: true })) })
  await waitForGit(() => document.querySelector('.gm-inspector h2')?.textContent === 'feature/inspector')
  await ctx.evaluate(() => { const select = document.querySelector('[aria-label="Referência em foco"]'); select.value = 'refs/heads/feature/contextual-review-with-a-very-long-name-and-shared-tip-for-signal-validation'; select.dispatchEvent(new Event('change', { bubbles: true })) })
  await waitForGit(() => document.querySelector('.gm-inspector h2')?.textContent.includes('contextual-review-with-a-very-long-name'))
  ctx.check('Shared-tip refs and long names remain accessible through contextual comparison', await ctx.evaluate(() => document.querySelector('.gm-inspector h2').textContent.includes('shared-tip') && document.querySelector('[aria-label="Referência em foco"]').value.includes('shared-tip')))
  await ctx.capture('pure-signal-long-reference-light')
  await close()
  const windowTimes = []
  for (const [index, count] of [[1,30],[2,60],[3,90],[4,null]]) {
    const start = performance.now()
    const calls = backend.metrics.atlas.length
    await ctx.click(`.gm-segmented button:nth-child(${index})`)
    await ctx.waitFor(index => document.querySelector(`.gm-segmented button:nth-child(${index})`).getAttribute('aria-pressed') === 'true', index)
    const deadline = Date.now() + 30000
    while (backend.metrics.atlas.length <= calls && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 30))
    await settle()
    windowTimes.push(Math.round(performance.now() - start))
    if (count) ctx.check(`${count} daily columns remain complete`, await ctx.evaluate(count => document.querySelectorAll('.gm-atlas-date').length === count, count))
  }
  await ctx.viewport(1000, 800)
  await lookup(head)
  await ctx.capture('pure-signal-medium-light')
  ctx.window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'ESCAPE' }); ctx.window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'ESCAPE' })
  await ctx.waitFor(() => !document.querySelector('.gm-inspector'))
  await ctx.waitFor(() => document.activeElement.matches('.gm-secondary-menu summary'))
  ctx.check('Escape restores keyboard focus to the lookup trigger', true)
  await ctx.evaluate(() => { document.body.dataset.theme = 'dark' })
  await ctx.capture('pure-signal-medium-dark')
  await ctx.viewport(1672, 941)
  await operations()
  await ctx.waitFor(() => !!document.querySelector('.gm-commit-review'))
  ctx.check('Only non-empty change groups are shown', await ctx.evaluate(() => document.querySelectorAll('.gm-change-group').length === 3))
  await ctx.capture('pure-signal-operations-dirty')
  ctx.check('Inspection preserves actual index, worktree and HEAD', git('status', '--porcelain') === before && git('rev-parse', 'HEAD') === head)
  await ctx.click('.gm-path-selection label:nth-child(2) input')
  await ctx.waitFor(() => !document.querySelector('.gm-action-row button').disabled)
  await ctx.click('.gm-action-row button')
  await waitForGit(() => document.querySelector('.gm-commit-review h3')?.textContent.includes('2 arquivos'))
  await ctx.input('[aria-label="Mensagem do commit"]', 'Record inspected Pure Signal changes')
  await ctx.click('.gm-commit-review button'); await ctx.click('.gm-confirm button')
  await waitForGit(() => document.querySelector('.gm-actions [role="status"]')?.textContent.includes('Commit registrado'))
  await settle()
  ctx.check('Real stage/commit keeps later worktree edits outside index', git('show', 'HEAD:file.txt') === 'prepared version' && git('show', 'HEAD:new.txt') === 'new file' && git('diff', '--name-only') === 'file.txt')
  await ctx.click('.gm-actions details summary')
  await ctx.input('[aria-label="Nova branch"]', 'pure-signal-branch')
  await ctx.click('.gm-actions details > button'); await ctx.click('.gm-confirm button')
  await waitForGit(() => [...document.querySelectorAll('[aria-label="Trocar branch"] option')].some(option => option.value === 'pure-signal-branch'))
  ctx.check('Branch action remains accessible and preserves checkout', git('rev-parse', 'pure-signal-branch') === git('rev-parse', 'HEAD') && git('branch', '--show-current') === 'main')
  git('restore', 'file.txt')
  await ctx.click('[aria-label="Atualizar Git"]'); await settle()
  await waitForGit(() => !!document.querySelector('.gm-inspector-scroll')?.textContent.includes('Checkout limpo'))
  ctx.check('Clean operations show neither empty groups nor disabled commit form', await ctx.evaluate(() => !document.querySelector('.gm-change-group') && !document.querySelector('.gm-commit-review') && !document.querySelector('[aria-label="Mensagem do commit"]')))
  await ctx.capture('pure-signal-operations-clean')
  await close()
  git('switch', '-c', 'conflict-source')
  fs.writeFileSync(path.join(root, 'file.txt'), 'conflicting source\n'); git('add', 'file.txt'); git('commit', '-m', 'Conflict source')
  git('switch', 'main')
  fs.writeFileSync(path.join(root, 'file.txt'), 'conflicting main\n'); git('add', 'file.txt'); git('commit', '-m', 'Conflict main')
  const conflict = spawnSync('git', ['merge', 'conflict-source'], { cwd: root, encoding: 'utf8', windowsHide: true })
  ctx.check('Real merge creates a conflict for critical-state proof', conflict.status === 1)
  await ctx.click('[aria-label="Atualizar Git"]'); await settle(); await operations()
  await waitForGit(() => document.querySelector('.gm-inspector')?.textContent.includes('Resolva a operação Git'))
  ctx.check('Conflict stays prominent and blocks mutations', await ctx.evaluate(() => !!document.querySelector('.gm-actions [role="alert"]') && [...document.querySelectorAll('.gm-action-row button')].every(button => button.disabled)))
  await ctx.capture('pure-signal-conflict-dark')
  await close(); git('merge', '--abort')
  await ctx.click('[aria-label="Atualizar Git"]'); await settle()
  await ctx.evaluate(async () => {
    const state = await window.codeAwareness.getActiveProject(), context = { projectId: state.project.id, revision: state.revision }
    const overview = await window.codeAwareness.getGitManagementOverview(context)
    sessionStorage.setItem(`git-management:pending:${context.projectId}`, JSON.stringify({ context, operationId: 'pending-proof', snapshot: overview.data.state, operation: { action: 'FETCH' } }))
  })
  await operations(); await ctx.waitFor(() => !!document.querySelector('.gm-pending'))
  ctx.check('Persisted unknown operation is recoverable without resending a new operation', await ctx.evaluate(() => document.querySelector('.gm-pending').textContent.includes('Recuperar mesma operação')))
  await ctx.capture('pure-signal-pending-dark')
  await close(); await ctx.evaluate(() => sessionStorage.clear())
  const tree = git('rev-parse', 'HEAD^{tree}'), records = []
  for (let index = 0; index < 230; index++) {
    const subject = `Older work ${index}\n`, date = Math.floor(Date.now() / 1000) - (40 - index / 10) * 86400
    records.push(`commit refs/heads/long-history\ncommitter Proof <proof@example.com> ${Math.floor(date)} +0000\ndata ${Buffer.byteLength(subject)}\n${subject}${index ? '' : `from ${head}\n`}\n`)
  }
  const imported = spawnSync('git', ['fast-import', '--quiet'], { cwd: root, input: records.join(''), encoding: 'utf8', windowsHide: true })
  if (imported.status) throw new Error(imported.stderr)
  await ctx.click('.gm-segmented button:nth-child(3)'); await settle()
  const afterOpen = backend.metrics.atlas.length
  await new Promise(resolve => setTimeout(resolve, 600))
  ctx.check('Partial history does not cascade indefinitely while idle', backend.metrics.atlas.length <= afterOpen + 1)
  for (let attempt = 0; attempt < 6; attempt++) { await wheelPast(); if (!(await ctx.evaluate(() => !!document.querySelector('.gm-atlas-context [role="status"]')))) break; await new Promise(resolve => setTimeout(resolve, 150)) }
  await waitForGit(() => !document.querySelector('.gm-atlas-context [role="status"]'))
  ctx.check('More than 100 commits load through exploration without a manual button', !await ctx.evaluate(() => !!document.querySelector('.gm-load-more')) && backend.metrics.atlas.length > afterOpen)
  await ctx.capture('pure-signal-progressive-history')
  await ctx.click('.gm-segmented button:nth-child(4)'); await settle()
  await wheelPast()
  ctx.check('All history remains incrementally bounded', backend.metrics.atlas.length < afterOpen + 12)
  await ctx.click('[data-proof-project="b"]')
  await waitForGit(() => document.querySelector('.gm-placeholder')?.textContent.includes('Nenhum commit'))
  ctx.check('Project switch clears history and inspector', await ctx.evaluate(() => !document.querySelector('.gm-commit') && !document.querySelector('.gm-inspector')))
  await ctx.capture('pure-signal-empty')
  await ctx.click('[data-proof-project="non-git"]')
  await waitForGit(() => document.querySelector('[role="alert"]')?.textContent.includes('não é um repositório Git'))
  await ctx.capture('pure-signal-error')
  await ctx.overflow()
  fs.writeFileSync(path.join(ctx.evidenceDir, 'atlas-latency.json'), JSON.stringify({ gitMs: backend.metrics, rendererWindowMs: windowTimes }, null, 2))
  const identity = backend.runtime.getIdentityPayload()
  ctx.check('Fresh production source in expected worktree', identity.freshness.state === 'MATCH')
}

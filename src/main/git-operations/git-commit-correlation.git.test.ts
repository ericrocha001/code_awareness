it('finds all current exact/ancestral worktrees, deduplicates HEAD proofs and ignores unassigned branches', async () => {
  const f = await fixture(), proofs = vi.spyOn(f.git, 'isCommitReachable')
  const inherited = await f.service.getCommitWorktrees({ sha: f.base, limit: 100 })
  expect(inherited).toMatchObject({ outcome: 'MATCHES', coverage: 'COMPLETE', scope: { total: 3, end: 3, unavailable: 0 } })
  expect(inherited.items).toHaveLength(3)
  expect(inherited.items.find(i => i.worktreeId === f.record.worktreeId)?.relation).toBe('REACHABLE_FROM_HEAD')
  expect(inherited.items.find(i => i.worktreeId === f.detached.worktreeId)).toMatchObject({ relation: 'HEAD_EXACT', detached: true })
  expect(proofs).toHaveBeenCalledTimes(1)
  await gitExec(f.b, ['reset', '--hard', f.head])
  const shared = await f.service.getCommitWorktrees({ sha: f.head, limit: 100 })
  expect(shared.items.filter(i => i.relation === 'HEAD_EXACT')).toHaveLength(2)
  const excluded = await f.service.getCommitWorktrees({ sha: f.base, mode: 'EXCLUSIVE', reference: 'refs/heads/reference', limit: 100 })
  expect(excluded).toMatchObject({ items: [], outcome: 'NONE_VERIFIED', coverage: 'COMPLETE' })
  const exclusive = await f.service.getCommitWorktrees({ sha: f.head, mode: 'EXCLUSIVE', reference: f.base, limit: 100 })
  expect(exclusive.items).toHaveLength(2); expect(exclusive.items.every(i => i.referenceRelation === 'EXCLUSIVE_RELATIVE_TO_REFERENCE')).toBe(true)
  await gitExec(f.root, ['branch', 'unassigned', f.head]); await gitExec(f.a, ['reset', '--hard', f.base]); await gitExec(f.b, ['reset', '--hard', f.base])
  expect(await f.service.getCommitWorktrees({ sha: f.head, limit: 100 })).toMatchObject({ items: [], outcome: 'NONE_VERIFIED', coverage: 'COMPLETE' })
  await expect(f.service.getCommitWorktrees({ sha: '0'.repeat(40) })).rejects.toMatchObject({ code: 'COMMIT_UNAVAILABLE' })
  const blob = (await gitExec(f.root, ['rev-parse', 'HEAD:base.txt'])).trim()
  await expect(f.service.getCommitWorktrees({ sha: blob })).rejects.toMatchObject({ code: 'COMMIT_UNAVAILABLE' })
}, 30000)

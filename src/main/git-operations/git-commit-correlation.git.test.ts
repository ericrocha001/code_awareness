it('proves non-linear merge ancestry and rejects replacement/shallow graph semantics without inventing absence', async () => {
  const f = await fixture()
  writeFileSync(join(f.b, 'b.txt'), 'independent\n'); await stageAll(f.b); await commit(f.b, 'b branch')
  const bHead = (await gitExec(f.b, ['rev-parse', 'HEAD'])).trim()
  await gitExec(f.a, ['merge', '--no-edit', bHead])
  const result = await f.service.getCommitWorktrees({ sha: bHead, limit: 100 })
  expect(result.items.find(i => i.worktreeId === f.record.worktreeId)?.relation).toBe('REACHABLE_FROM_HEAD')
  expect(result.items.find(i => i.worktreeId === f.detached.worktreeId)?.relation).toBe('HEAD_EXACT')
  await gitExec(f.root, ['update-ref', `refs/replace/${f.head}`, f.base])
  await expect(f.service.getCommitWorktrees({ sha: f.base })).rejects.toMatchObject({ code: 'COMMIT_GRAPH_UNAVAILABLE' })
  await gitExec(f.root, ['update-ref', '-d', `refs/replace/${f.head}`])
  writeFileSync(join(f.root, '.git', 'shallow'), f.base + '\n')
  await expect(f.service.getWorktreeCommits({ worktreeId: f.record.worktreeId, generation: f.record.generation })).rejects.toMatchObject({ code: 'COMMIT_GRAPH_UNAVAILABLE' })
}, 30000)
it('reuses only physically validated directories and recomputes generation on replacement', async () => {
  const f = await fixture(), directories = vi.spyOn(f.git, 'getRepositoryDirectories')
  await f.service.getCommitWorktrees({ sha: f.base, limit: 100 })
  expect(directories).not.toHaveBeenCalled()
  const page = await f.service.getCommitWorktrees({ sha: f.base, limit: 1 })
  await gitExec(f.root, ['worktree', 'remove', '--force', f.b]); await gitExec(f.root, ['worktree', 'add', '--detach', f.b, f.base])
  await expect(f.service.getCommitWorktrees({ sha: f.base, limit: 1, cursor: page.nextCursor! })).rejects.toMatchObject({ code: 'GIT_STATE_CHANGED' })
  await expect(f.service.getWorktreeCommits({ worktreeId: f.detached.worktreeId, generation: f.detached.generation })).rejects.toMatchObject({ code: 'WORKTREE_STALE' })
  const foreign = await createTempGitRepo(); roots.push(foreign)
  writeFileSync(join(await f.git.getWorktreeDirectory(f.a), 'commondir'), join(foreign, '.git') + '\n')
  await expect(f.service.getCommitWorktrees({ sha: f.base, limit: 100 })).rejects.toMatchObject({ code: 'WORKTREE_IDENTITY_MISMATCH' })
  expect(directories).toHaveBeenCalled()
}, 30000)

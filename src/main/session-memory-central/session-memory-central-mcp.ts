export const MAX_BUILDX_ENTRY_BYTES = 1024 * 1024 // 1 MiB

const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
const VALID_REFERENCE_KINDS = new Set<SmcReferenceKind>(['COMMIT', 'PROOF', 'ARTIFACT', 'OTHER'])
const VALID_ENTRY_KINDS: SmcEntryKind[] = ['DECISION', 'EVIDENCE', 'RESULT', 'PENDING', 'INTERVENTION']

function readOnlyTool(
  name: string,
  description: string,
  properties: Record<string, unknown>,
  required: string[] = []
): McpToolDefinition {
  return {
    name,
    description,
    securitySchemes: [{ type: 'oauth2', scopes: [] }],
    annotations: { readOnlyHint: true },
    inputSchema: {
      type: 'object',
      properties,
      ...(required.length ? { required } : {}),
      additionalProperties: false
    }
  }
}

function mutationTool(
  name: string,
  description: string,
  properties: Record<string, unknown>,
  required: string[] = []
): McpToolDefinition {
  return {
    name,
    description,
    securitySchemes: [{ type: 'oauth2', scopes: [] }],
    annotations: {},
    inputSchema: {
      type: 'object',
      properties,
      ...(required.length ? { required } : {}),
      additionalProperties: false
    }
  }
}


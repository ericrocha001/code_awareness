export interface ExecuteBuildxSmcOptions {
  assertActiveProject?: () => void
  maxResponseBytes?: number
}

function ok(payload: unknown): McpToolResult<McpTextContent> {
  return {
    content: [{ type: 'text', text: JSON.stringify(payload) }]
  }
}

function failure(code: string, message: string): McpToolResult<McpTextContent> {
  return {
    isError: true,
    content: [{ type: 'text', text: JSON.stringify({ code, message }) }]
  }
}

function mapSmcError(error: unknown): McpToolResult<McpTextContent> {
  if (error instanceof SmcSessionNotFoundError) return failure('SESSION_NOT_FOUND', 'Session was not found in the active repository')
  if (error instanceof SmcSessionClosedError) return failure('SESSION_CLOSED', 'Session is closed and does not accept new entries')
  if (error instanceof SmcSessionAlreadyExistsError) return failure('SESSION_ALREADY_EXISTS', 'A session with this ID already exists but was created with incompatible state')
  if (error instanceof SmcInvalidSessionIdError) return failure('INVALID_ARGUMENT', 'sessionId must be a valid UUID')
  if (error instanceof SmcInvalidEntryError) return failure('INVALID_ARGUMENT', (error as Error).message)
  if (error instanceof SmcEntryConflictError) return failure('ENTRY_CONFLICT', 'An entry with this entryId already exists with divergent content')
  if (error instanceof SmcInvalidSupersedesError) return failure('INVALID_SUPERSEDES', 'supersedesEntryId does not belong to the specified session')
  const err = error as any
  return failure(err?.code ?? 'EXECUTION_FAILED', err?.message ?? String(error))
}

export function executeBuildxSmcTool(
  service: SessionMemoryCentralService,
  repositoryId: string,
  name: string,
  args: unknown,
  options?: ExecuteBuildxSmcOptions
): McpToolResult<McpTextContent> {
  try {
    options?.assertActiveProject?.()
  } catch {
    return failure('PROJECT_CONTEXT_CHANGED', 'Active repository project context changed or was invalidated')
  }

  if (!repositoryId || typeof repositoryId !== 'string' || !repositoryId.trim()) {
    return failure('REPOSITORY_CONTEXT_REQUIRED', 'A valid active repositoryId is required and cannot be omitted')
  }

  const validRepoId = repositoryId.trim()
  const rawArgs = args && typeof args === 'object' && !Array.isArray(args) ? (args as Record<string, unknown>) : {}

  try {
    switch (name) {
      case 'list_buildx_sessions': {
        const rawLimit = rawArgs.limit
        let limit: number | undefined
        if (rawLimit !== undefined) {
          if (typeof rawLimit !== 'number' || !Number.isInteger(rawLimit) || rawLimit < 1) {
            return failure('INVALID_ARGUMENT', 'limit must be a positive integer')
          }
          limit = Math.min(rawLimit, 100)
        }
        const sessions = service.listSessions(validRepoId, { limit })
        return ok({ sessions })
      }

      case 'list_buildx_session_entries': {
        const sessionId = rawArgs.sessionId
        if (typeof sessionId !== 'string' || !UUID_REGEX.test(sessionId.trim())) {
          return failure('INVALID_ARGUMENT', 'sessionId must be a valid UUID')
        }
        const cleanSessionId = sessionId.trim().toLowerCase()

        const session = service.getSession(validRepoId, cleanSessionId)
        if (!session) {
          return failure('SESSION_NOT_FOUND', 'Session was not found in the active repository')
        }

        const rawKind = rawArgs.kind
        let kind: SmcEntryKind | undefined
        if (rawKind !== undefined) {
          if (typeof rawKind !== 'string' || !VALID_ENTRY_KINDS.includes(rawKind as SmcEntryKind)) {
            return failure('INVALID_ARGUMENT', `Invalid kind filter: "${String(rawKind)}"`)
          }
          kind = rawKind as SmcEntryKind
        }

        const rawLimit = rawArgs.limit
        let limit: number | undefined
        if (rawLimit !== undefined) {
          if (typeof rawLimit !== 'number' || !Number.isInteger(rawLimit) || rawLimit < 1) {
            return failure('INVALID_ARGUMENT', 'limit must be a positive integer')
          }
          limit = Math.min(rawLimit, 100)
        }

        const cursor = typeof rawArgs.cursor === 'string' && rawArgs.cursor.trim() ? rawArgs.cursor.trim() : undefined

        const result = service.listEntries(validRepoId, cleanSessionId, { kind, limit, cursor })
        return ok(result)
      }

      case 'get_buildx_session_entry': {
        const sessionId = rawArgs.sessionId
        if (typeof sessionId !== 'string' || !UUID_REGEX.test(sessionId.trim())) {
          return failure('INVALID_ARGUMENT', 'sessionId must be a valid UUID')
        }
        const cleanSessionId = sessionId.trim().toLowerCase()

        const entryId = rawArgs.entryId
        if (typeof entryId !== 'string' || !UUID_REGEX.test(entryId.trim())) {
          return failure('INVALID_ARGUMENT', 'entryId must be a valid UUID')
        }
        const cleanEntryId = entryId.trim().toLowerCase()

        const session = service.getSession(validRepoId, cleanSessionId)
        if (!session) {
          return failure('SESSION_NOT_FOUND', 'Session was not found in the active repository')
        }

        const record = service.getEntry(validRepoId, cleanSessionId, cleanEntryId)
        if (!record) {
          return failure('ENTRY_NOT_FOUND', 'Entry was not found in the specified session')
        }

        const maxBytes = options?.maxResponseBytes ?? MAX_BUILDX_ENTRY_BYTES
        const serialized = JSON.stringify(record)
        if (Buffer.byteLength(serialized, 'utf8') > maxBytes) {
          return failure('RESPONSE_LIMIT_REACHED', 'Entry size exceeds maximum Channel response budget')
        }

        return ok(record)
      }

      case 'create_buildx_session': {
        const sessionId = rawArgs.sessionId
        if (typeof sessionId !== 'string' || !UUID_REGEX.test(sessionId.trim())) {
          return failure('INVALID_ARGUMENT', 'sessionId must be a valid UUID')
        }
        const cleanSessionId = sessionId.trim().toLowerCase()

        // Idempotency: if session already exists with the same ID, return it as a replay
        const existing = service.getSession(validRepoId, cleanSessionId)
        if (existing) {
          return ok({ sessionId: existing.sessionId, status: existing.status, revision: existing.revision, replayed: true })
        }

        const created = service.createSession(validRepoId, { sessionId: cleanSessionId })
        return ok({ sessionId: created.sessionId, status: created.status, revision: created.revision })
      }

      case 'append_buildx_session_entry': {
        const sessionId = rawArgs.sessionId
        if (typeof sessionId !== 'string' || !UUID_REGEX.test(sessionId.trim())) {
          return failure('INVALID_ARGUMENT', 'sessionId must be a valid UUID')
        }
        const cleanSessionId = sessionId.trim().toLowerCase()

        const entryId = rawArgs.entryId
        if (typeof entryId !== 'string' || !UUID_REGEX.test(entryId.trim())) {
          return failure('INVALID_ARGUMENT', 'entryId must be a valid UUID')
        }
        const cleanEntryId = entryId.trim().toLowerCase()

        const kind = rawArgs.kind
        if (typeof kind !== 'string' || !VALID_ENTRY_KINDS.includes(kind as SmcEntryKind)) {
          return failure('INVALID_ARGUMENT', `kind must be one of: ${VALID_ENTRY_KINDS.join(', ')}`)
        }

        const title = rawArgs.title
        if (typeof title !== 'string' || !title.trim()) {
          return failure('INVALID_ARGUMENT', 'title must be a non-empty string')
        }

        const body = rawArgs.body
        if (typeof body !== 'string') {
          return failure('INVALID_ARGUMENT', 'body must be a string')
        }

        // emitterId is optional declared metadata, never verified
        let emitterId: string | undefined
        if (rawArgs.emitterId !== undefined) {
          if (typeof rawArgs.emitterId !== 'string' || !rawArgs.emitterId.trim()) {
            return failure('INVALID_ARGUMENT', 'emitterId must be a non-empty string when provided')
          }
          emitterId = rawArgs.emitterId.trim()
        }

        // supersedesEntryId is optional
        let supersedesEntryId: string | undefined
        if (rawArgs.supersedesEntryId !== undefined) {
          if (typeof rawArgs.supersedesEntryId !== 'string' || !UUID_REGEX.test(rawArgs.supersedesEntryId.trim())) {
            return failure('INVALID_ARGUMENT', 'supersedesEntryId must be a valid UUID when provided')
          }
          supersedesEntryId = rawArgs.supersedesEntryId.trim().toLowerCase()
        }

        // references is optional
        let references: Array<{ kind: SmcReferenceKind; target: string }> | undefined
        if (rawArgs.references !== undefined) {
          if (!Array.isArray(rawArgs.references)) {
            return failure('INVALID_ARGUMENT', 'references must be an array')
          }
          references = []
          for (const ref of rawArgs.references) {
            if (!ref || typeof ref !== 'object' || Array.isArray(ref)) {
              return failure('INVALID_ARGUMENT', 'each reference must be an object with kind and target')
            }
            const r = ref as Record<string, unknown>
            if (typeof r.kind !== 'string' || !VALID_REFERENCE_KINDS.has(r.kind as SmcReferenceKind)) {
              return failure('INVALID_ARGUMENT', `reference kind must be one of: ${[...VALID_REFERENCE_KINDS].join(', ')}`)
            }
            if (typeof r.target !== 'string' || !r.target.trim()) {
              return failure('INVALID_ARGUMENT', 'reference target must be a non-empty string')
            }
            references.push({ kind: r.kind as SmcReferenceKind, target: r.target.trim() })
          }
        }

        // Always persist role as AGENT — provenance is declared/unverified
        const appended = service.appendEntry(validRepoId, cleanSessionId, {
          entryId: cleanEntryId,
          kind: kind as SmcEntryKind,
          title: title.trim(),
          body,
          provenance: { role: 'AGENT', ...(emitterId ? { emitterId } : {}) },
          ...(references && references.length > 0 ? { references } : {}),
          ...(supersedesEntryId ? { supersedesEntryId } : {})
        })

        // Compact receipt: no body echo
        return ok({
          entryId: appended.entryId,
          sessionId: appended.sessionId,
          kind: appended.kind,
          title: appended.title,
          createdAt: appended.createdAt
        })
      }

      default:
        return failure('UNKNOWN_TOOL', `Unknown BuildX SMC tool: "${name}"`)
    }
  } catch (error: unknown) {
    return mapSmcError(error)
  }
}
